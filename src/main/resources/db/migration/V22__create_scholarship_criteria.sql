CREATE TABLE public.scholarship_criteria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id uuid NOT NULL DEFAULT gen_random_uuid(),
    department_id bigint NOT NULL,
    admission_year integer NOT NULL,
    name varchar(100) NOT NULL,
    min_gpa numeric(3,2) NOT NULL,
    min_credits numeric(4,1) NOT NULL,
    max_warnings integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uk_scholarship_criteria_entity_id
        UNIQUE (entity_id),

    CONSTRAINT uk_scholarship_criteria_policy
        UNIQUE (department_id, admission_year, name),

    CONSTRAINT fk_scholarship_criteria_department
        FOREIGN KEY (department_id)
            REFERENCES public.department (id),

    CONSTRAINT ck_scholarship_criteria_admission_year
        CHECK (admission_year BETWEEN 2000 AND 9999),

    CONSTRAINT ck_scholarship_criteria_name_not_blank
        CHECK (length(btrim(name)) > 0),

    CONSTRAINT ck_scholarship_criteria_min_gpa
        CHECK (min_gpa BETWEEN 0.00 AND 4.50),

    CONSTRAINT ck_scholarship_criteria_min_credits
        CHECK (min_credits >= 0.0),

    CONSTRAINT ck_scholarship_criteria_max_warnings
        CHECK (max_warnings >= 0)
);

ALTER TABLE public.scholarship_criteria ENABLE ROW LEVEL SECURITY;
