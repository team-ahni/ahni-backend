CREATE TABLE public.professor (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id uuid NOT NULL DEFAULT gen_random_uuid(),
    department_id bigint,
    name varchar(100) COLLATE ahni_korean NOT NULL,
    office varchar(200),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,

    CONSTRAINT uk_professor_entity_id
        UNIQUE (entity_id),

    CONSTRAINT fk_professor_department
        FOREIGN KEY (department_id)
            REFERENCES public.department (id),

    CONSTRAINT ck_professor_name_not_blank
        CHECK (length(btrim(name)) > 0)
);

CREATE INDEX idx_professor_department
    ON public.professor (department_id);
