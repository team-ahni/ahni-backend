CREATE TABLE public.inquiry_attachment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id uuid NOT NULL,
    inquiry_id bigint NOT NULL,
    storage_key varchar(200) NOT NULL,
    filename varchar(255) NOT NULL,
    content_type varchar(100) NOT NULL,
    size_bytes bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uk_inquiry_attachment_entity_id
        UNIQUE (entity_id),

    CONSTRAINT uk_inquiry_attachment_storage_key
        UNIQUE (storage_key),

    CONSTRAINT fk_inquiry_attachment_inquiry
        FOREIGN KEY (inquiry_id)
            REFERENCES public.inquiry (id),

    CONSTRAINT ck_inquiry_attachment_content_type
        CHECK (content_type IN ('image/jpeg', 'image/png', 'application/pdf')),

    CONSTRAINT ck_inquiry_attachment_size
        CHECK (size_bytes > 0 AND size_bytes <= 5242880),

    CONSTRAINT ck_inquiry_attachment_filename_not_blank
        CHECK (length(btrim(filename)) > 0)
);

CREATE INDEX idx_inquiry_attachment_inquiry
    ON public.inquiry_attachment (inquiry_id, created_at);

-- 클라이언트는 Spring API로만 접근한다. V21에서 빠진 inquiry RLS도 함께 켠다.
ALTER TABLE public.inquiry ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiry_attachment ENABLE ROW LEVEL SECURITY;

-- Supabase에서만 비공개 버킷을 만든다. 일반 PostgreSQL 테스트 DB에는 storage 스키마가 없다.
DO $$
BEGIN
    IF to_regclass('storage.buckets') IS NOT NULL THEN
        INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
        VALUES (
            'inquiry-attachments',
            'inquiry-attachments',
            false,
            5242880,
            ARRAY['image/jpeg', 'image/png', 'application/pdf']
        )
        ON CONFLICT (id) DO NOTHING;
    END IF;
END
$$;
