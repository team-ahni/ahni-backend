CREATE TABLE public.lecture (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    course_id bigint NOT NULL REFERENCES public.course(id),
    professor_id bigint NOT NULL REFERENCES public.professor(id),
    academic_year integer NOT NULL CHECK (academic_year BETWEEN 2000 AND 9999),
    term varchar(20) NOT NULL CHECK (term IN ('FIRST', 'SUMMER', 'SECOND', 'WINTER')),
    section varchar(30) NOT NULL CHECK (btrim(section) <> ''),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_lecture_offering UNIQUE (course_id, academic_year, term, section)
);

CREATE TABLE public.lecture_schedule (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    lecture_id bigint NOT NULL REFERENCES public.lecture(id),
    day_of_week integer NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time time NOT NULL,
    end_time time NOT NULL,
    classroom varchar(200),
    CONSTRAINT ck_lecture_schedule_time CHECK (start_time < end_time)
);

CREATE TABLE public.timetable (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    student_id bigint NOT NULL REFERENCES public.student(id),
    lecture_id bigint NOT NULL REFERENCES public.lecture(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_timetable_student_lecture UNIQUE (student_id, lecture_id)
);

CREATE INDEX idx_lecture_year_term ON public.lecture (academic_year, term);
CREATE INDEX idx_lecture_professor ON public.lecture (professor_id);
CREATE INDEX idx_lecture_schedule_lecture ON public.lecture_schedule (lecture_id);
CREATE INDEX idx_timetable_lecture ON public.timetable (lecture_id);

ALTER TABLE public.professor ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lecture ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lecture_schedule ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.timetable ENABLE ROW LEVEL SECURITY;
