CREATE TABLE public.student_relink_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id uuid NOT NULL DEFAULT gen_random_uuid(),
    student_id bigint NOT NULL,
    new_auth_user_id uuid NOT NULL,
    email varchar(320) NOT NULL,
    status varchar(30) NOT NULL DEFAULT 'PENDING',
    previous_auth_user_id uuid,
    resolved_by_admin_id bigint,
    resolved_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uk_student_relink_request_entity_id
        UNIQUE (entity_id),

    CONSTRAINT fk_student_relink_request_student
        FOREIGN KEY (student_id)
            REFERENCES public.student (id),

    CONSTRAINT fk_student_relink_request_resolved_by_admin
        FOREIGN KEY (resolved_by_admin_id)
            REFERENCES public.admin (id),

    CONSTRAINT ck_student_relink_request_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),

    CONSTRAINT ck_student_relink_request_resolution
        CHECK (
            (status = 'PENDING' AND resolved_by_admin_id IS NULL AND resolved_at IS NULL
                AND previous_auth_user_id IS NULL)
            OR (status = 'REJECTED' AND resolved_by_admin_id IS NOT NULL AND resolved_at IS NOT NULL
                AND previous_auth_user_id IS NULL)
            OR (status = 'APPROVED' AND resolved_by_admin_id IS NOT NULL AND resolved_at IS NOT NULL
                AND previous_auth_user_id IS NOT NULL)
        )
);

CREATE UNIQUE INDEX uk_student_relink_request_pending_auth_user
    ON public.student_relink_request (new_auth_user_id)
    WHERE status = 'PENDING';

CREATE INDEX idx_student_relink_request_student
    ON public.student_relink_request (student_id);

ALTER TABLE public.student_relink_request ENABLE ROW LEVEL SECURITY;
